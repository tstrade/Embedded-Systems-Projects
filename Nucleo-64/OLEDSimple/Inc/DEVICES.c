void  ssd1306_command(unsigned char c)
{
	unsigned char control = 0x00;

    I2C2WriteRegister(OLED_addr, control, c);
    }

void  ssd1306_data(unsigned char c)
{
   I2C2WriteRegister(OLED_addr, 0x40, c);

}
void setColAddress(int xCol)
{
	if(xCol>(SSD1306_LCDWIDTH-1))return;
  ssd1306_command(SSD1306_COLUMNADDR);
  ssd1306_command(xCol);
  ssd1306_command(SSD1306_LCDWIDTH-1);
}

void setPageAddress(int yPage)
{  if(yPage>(SSD1306_LCDHEIGHT/8-1))return;
  ssd1306_command(SSD1306_PAGEADDR);
  ssd1306_command(yPage);
  ssd1306_command((SSD1306_LCDHEIGHT/8)-1);
}

void transferBuffer(int *p, int size,unsigned char xCol,unsigned char yPage)
{
	int j=0;
      setColAddress(xCol);
      setPageAddress(yPage);

      for(j=0;j<size;j++)
      {
        I2C2WriteRegister(OLED_addr, 0x40, *p);
        p++;
      }
}

